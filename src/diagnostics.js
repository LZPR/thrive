/**
 * 取一个错误码的兜底 hint。
 * @param {string} code
 * @returns {string} 认不出的错误码返回空串，由调用方决定是否只回 code
 */
export function hintFor(code) {
    return ERROR_HINTS[String(code ?? '')] ?? '';
}
